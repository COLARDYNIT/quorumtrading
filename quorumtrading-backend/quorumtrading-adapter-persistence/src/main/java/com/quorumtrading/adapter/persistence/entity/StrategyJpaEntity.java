package com.quorumtrading.adapter.persistence.entity;

import io.quarkus.hibernate.orm.panache.PanacheEntityBase;
import jakarta.persistence.*;
import java.time.Instant;
import java.util.UUID;

/**
 * JPA entity for Strategy persistence.
 *
 * Maps to the orchestrator_strategies table created by Flyway migrations.
 * This is SEPARATE from the domain Strategy to maintain hexagonal architecture boundaries.
 *
 * NOTE: Uses UUID as primary key to match database schema (migrated from BIGSERIAL).
 * Extends PanacheEntityBase instead of PanacheEntity to allow custom UUID @Id.
 */
@Entity
@Table(name = "orchestrator_strategies")
public class StrategyJpaEntity extends PanacheEntityBase {

    /**
     * UUID primary key.
     * Must be set by application code before persist.
     * NOT auto-generated by database to support pre-set IDs with optimistic locking.
     */
    @Id
    @Column(name = "id", nullable = false)
    public UUID id;

    /**
     * Optimistic locking version.
     * Managed by Hibernate to prevent concurrent modification conflicts.
     * Must be explicitly set to 0 for new entities before persist().
     * Hibernate increments it automatically on persist/merge operations.
     */
    @Version
    @Column(name = "opt_lock_version", nullable = false)
    private Integer optLockVersion;

    /**
     * Strategy name identifier.
     * Must be unique, max 255 characters (increased from 50 in V43 migration).
     */
    @Column(name = "name", length = 255, unique = true, nullable = false)
    private String name;

    /**
     * Human-readable description for the strategy library.
     */
    @Column(name = "description", length = 500)
    private String description;

    /**
     * Markdown content defining the strategy.
     */
    @Column(name = "markdown_content", nullable = false, columnDefinition = "TEXT")
    private String markdownContent;

    /**
     * Strategy lifecycle status (ACTIVE, ARCHIVED).
     * Defaults to ACTIVE for new strategies.
     */
    @Column(name = "status", length = 20, nullable = false)
    private String status;

    /**
     * Creation timestamp (auto-set by @PrePersist).
     */
    @Column(name = "created_at", nullable = false)
    private Instant createdAt;

    /**
     * User who created the strategy.
     */
    @Column(name = "created_by", length = 100)
    private String createdBy;

    /**
     * Last update timestamp (auto-managed by trigger in V4 migration).
     */
    @Column(name = "updated_at")
    private Instant updatedAt;

    // Lineage tracking fields (added in V39 migration)

    /**
     * Reference to parent strategy for derived strategies.
     * NULL for original strategies.
     */
    @Column(name = "parent_strategy_id")
    private UUID parentStrategyId;

    /**
     * Generation number (0 for original, increments for derived strategies).
     */
    @Column(name = "generation", nullable = false)
    private Integer generation = 0;

    /**
     * When strategy was last tested via simulation.
     */
    @Column(name = "last_tested_at")
    private Instant lastTestedAt;

    /**
     * How often to auto-test this strategy (DAILY, WEEKLY, MANUAL_ONLY).
     */
    @Column(name = "test_frequency", length = 20)
    private String testFrequency;

    /**
     * Whether strategy is enabled for scheduled simulations.
     * Auto-disabled when underperforming (Phase 4).
     */
    @Column(name = "enabled", nullable = false)
    private boolean enabled = true;

    // Ownership field (added in V45 migration)

    /**
     * Owner of the strategy (user who created it).
     */
    @Column(name = "owner_id", nullable = false)
    private UUID ownerId;

    /**
     * Whether this strategy is publicly visible in the strategy library.
     */
    @Column(name = "public_visible", nullable = false)
    private boolean publicVisible = false;

    /**
     * Set default values before persisting new entity.
     */
    @PrePersist
    public void prePersist() {
        if (createdAt == null) {
            createdAt = Instant.now();
        }
        if (createdBy == null) {
            createdBy = "system";
        }
        if (status == null) {
            status = "ACTIVE";
        }
        if (generation == null) {
            generation = 0;
        }
        if (testFrequency == null) {
            testFrequency = "MANUAL_ONLY";
        }
    }

    // Getters and setters

    public String getName() {
        return name;
    }

    public void setName(String name) {
        this.name = name;
    }

    public String getDescription() {
        return description;
    }

    public void setDescription(String description) {
        this.description = description;
    }

    public String getMarkdownContent() {
        return markdownContent;
    }

    public void setMarkdownContent(String markdownContent) {
        this.markdownContent = markdownContent;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }

    public void setCreatedAt(Instant createdAt) {
        this.createdAt = createdAt;
    }

    public String getCreatedBy() {
        return createdBy;
    }

    public void setCreatedBy(String createdBy) {
        this.createdBy = createdBy;
    }

    public Instant getUpdatedAt() {
        return updatedAt;
    }

    public void setUpdatedAt(Instant updatedAt) {
        this.updatedAt = updatedAt;
    }

    public Integer getOptLockVersion() {
        return optLockVersion;
    }

    public void setOptLockVersion(Integer optLockVersion) {
        this.optLockVersion = optLockVersion;
    }

    public String getStatus() {
        return status;
    }

    public void setStatus(String status) {
        this.status = status;
    }

    // Lineage field getters and setters

    public UUID getParentStrategyId() {
        return parentStrategyId;
    }

    public void setParentStrategyId(UUID parentStrategyId) {
        this.parentStrategyId = parentStrategyId;
    }

    public Integer getGeneration() {
        return generation;
    }

    public void setGeneration(Integer generation) {
        this.generation = generation;
    }

    public Instant getLastTestedAt() {
        return lastTestedAt;
    }

    public void setLastTestedAt(Instant lastTestedAt) {
        this.lastTestedAt = lastTestedAt;
    }

    public String getTestFrequency() {
        return testFrequency;
    }

    public void setTestFrequency(String testFrequency) {
        this.testFrequency = testFrequency;
    }

    public boolean isEnabled() {
        return enabled;
    }

    public void setEnabled(boolean enabled) {
        this.enabled = enabled;
    }

    // Ownership field getters and setters

    public UUID getOwnerId() {
        return ownerId;
    }

    public void setOwnerId(UUID ownerId) {
        this.ownerId = ownerId;
    }

    public boolean isPublicVisible() {
        return publicVisible;
    }

    public void setPublicVisible(boolean publicVisible) {
        this.publicVisible = publicVisible;
    }
}
