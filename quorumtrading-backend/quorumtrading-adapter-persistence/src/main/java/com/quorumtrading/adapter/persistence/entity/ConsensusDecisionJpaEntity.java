package com.quorumtrading.adapter.persistence.entity;

import io.quarkus.hibernate.orm.panache.PanacheEntityBase;
import jakarta.persistence.*;
import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.type.SqlTypes;
import java.math.BigDecimal;
import java.time.Instant;
import java.util.UUID;

/**
 * JPA entity for ConsensusDecision persistence.
 *
 * Maps to the consensus_decisions table created by Flyway migrations.
 * This is SEPARATE from the domain ConsensusDecision to maintain hexagonal architecture boundaries.
 *
 * Uses simple types (UUID, BigDecimal, String, Long[]) instead of value objects.
 * Mappers handle conversion between domain and persistence layers.
 */
@Entity
@Table(name = "consensus_decisions")
public class ConsensusDecisionJpaEntity extends PanacheEntityBase {

    /**
     * Primary key (auto-generated by database).
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "id")
    public Long id;

    /**
     * Simulation UUID (unwrapped from SimulationId value object).
     */
    @Column(name = "simulation_id", nullable = false)
    public UUID simulationId;

    /**
     * When the consensus decision was made.
     */
    @Column(name = "decision_timestamp", nullable = false)
    public Instant decisionTimestamp;

    /**
     * Array of LLM decision IDs that contributed to this consensus.
     */
    @Column(name = "llm_decision_ids", nullable = false, columnDefinition = "bigint[]")
    public Long[] llmDecisionIds;

    /**
     * Consensus method used (MAJORITY, WEIGHTED, CONFIDENCE_BASED, ORCHESTRATOR_OVERRIDE).
     */
    @Column(name = "consensus_method", length = 50)
    public String consensusMethod;

    /**
     * Final action details (stored as JSONB).
     */
    @Column(name = "final_action", nullable = false)
    @JdbcTypeCode(SqlTypes.JSON)
    public String finalAction;

    /**
     * Whether the decision was executed.
     */
    @Column(name = "executed", nullable = false)
    public Boolean executed = false;

    /**
     * Execution price (if executed).
     */
    @Column(name = "execution_price", precision = 20, scale = 8)
    public BigDecimal executionPrice;

    /**
     * Additional notes about the decision.
     */
    @Column(name = "notes", columnDefinition = "TEXT")
    public String notes;

    /**
     * Trading symbol (e.g., BTC, AAPL).
     */
    @Column(name = "symbol", length = 20)
    public String symbol;

    /**
     * Investment type (CRYPTO, STOCK).
     */
    @Column(name = "investment_type", length = 20)
    public String investmentType;

    /**
     * Quantity to trade (if specified by orchestrator).
     */
    @Column(name = "quantity", precision = 20, scale = 8)
    public BigDecimal quantity;

    /**
     * Execution outcome (PENDING, EXECUTED, NO_TRADE_REQUIRED, REJECTED).
     */
    @Column(name = "execution_outcome", length = 50)
    public String executionOutcome;

    // LLM cost tracking fields
    @Column(name = "prompt_tokens")
    public Integer promptTokens = 0;

    @Column(name = "completion_tokens")
    public Integer completionTokens = 0;

    @Column(name = "total_tokens")
    public Integer totalTokens = 0;

    @Column(name = "raw_cost_usd", precision = 18, scale = 8)
    public BigDecimal rawCostUsd = BigDecimal.ZERO;

    /**
     * Wall-clock timestamp when this record was created (when the LLM call actually happened).
     * Distinct from decisionTimestamp which stores the simulated analysis time for backtests.
     * Used for budget/usage aggregation queries.
     */
    @Column(name = "created_at", nullable = false)
    public Instant createdAt;

    /**
     * Default constructor required by JPA.
     */
    public ConsensusDecisionJpaEntity() {
    }
}
