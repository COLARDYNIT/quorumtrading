package com.quorumtrading.adapter.persistence.repository;

import com.quorumtrading.adapter.persistence.entity.BrokerAccountJpaEntity;
import com.quorumtrading.adapter.persistence.mapper.BrokerAccountMapper;
import com.quorumtrading.application.port.out.BrokerAccountRepository;
import com.quorumtrading.model.entity.BrokerAccount;
import com.quorumtrading.model.enums.AccountStatus;
import com.quorumtrading.model.valueobject.BrokerAccountId;
import com.quorumtrading.model.valueobject.UserId;
import jakarta.enterprise.context.ApplicationScoped;
import jakarta.inject.Inject;
import jakarta.persistence.EntityManager;
import jakarta.persistence.TypedQuery;
import jakarta.transaction.Transactional;
import org.slf4j.Logger;
import org.slf4j.LoggerFactory;

import java.util.Collection;
import java.util.List;
import java.util.Optional;
import java.util.UUID;
import java.util.stream.Collectors;

/**
 * JPA EntityManager-based implementation of the BrokerAccountRepository port.
 *
 * <p>This adapter bridges the domain port interface to the JPA persistence layer.
 * Uses EntityManager instead of Panache static methods to support cross-module
 * entity discovery in Quarkus.</p>
 *
 * <p><b>Transaction Handling:</b> All write operations are wrapped in transactions.
 * Read operations use the existing transaction context if available.</p>
 */
@ApplicationScoped
@Transactional(Transactional.TxType.REQUIRED)
public class BrokerAccountRepositoryImpl implements BrokerAccountRepository {

    private static final Logger log = LoggerFactory.getLogger(BrokerAccountRepositoryImpl.class);

    @Inject
    BrokerAccountMapper mapper;

    @Inject
    EntityManager entityManager;

    @Override
    @Transactional
    public BrokerAccount save(BrokerAccount account) {
        log.debug("Saving broker account: {}", account.getId());
        BrokerAccountJpaEntity entity = mapper.toJpaEntity(account);

        // Check if this is an update (entity with this ID exists)
        if (account.getId() != null) {
            UUID uuid = account.getId().value();
            BrokerAccountJpaEntity existing = entityManager.find(BrokerAccountJpaEntity.class, uuid);

            if (existing != null) {
                // Update existing account (userId and createdAt are immutable)
                existing.setName(entity.getName());
                existing.setBrokerType(entity.getBrokerType());
                existing.setCredentialsEncrypted(entity.getCredentialsEncrypted());
                existing.setTotalBalanceAmount(entity.getTotalBalanceAmount());
                existing.setTotalBalanceCurrency(entity.getTotalBalanceCurrency());
                existing.setEquityAmount(entity.getEquityAmount());
                existing.setReservedBalanceAmount(entity.getReservedBalanceAmount());
                existing.setStatus(entity.getStatus());
                existing.setMockConfig(entity.getMockConfig());
                // Saxo OAuth projection columns track the (possibly rotated) credentials, so they
                // are refreshed from the mapped entity on every update.
                existing.setBrokerEnvironment(entity.getBrokerEnvironment());
                existing.setAccessTokenExpiresAt(entity.getAccessTokenExpiresAt());
                // NOTE: refresh_generation / refresh_locked_by / refresh_locked_at are deliberately
                // NOT copied here. Those columns are owned by the token-lease adapter (OA3), which
                // writes them via atomic UPDATE ... WHERE outside the domain mapper. Copying the
                // freshly-mapped (always-null) lease fields would clobber a concurrently-held lease
                // and break the rotating-refresh chain, so we leave the managed row's values intact.
                existing.setUpdatedAt(entity.getUpdatedAt());
                entity = entityManager.merge(existing);
                log.debug("Updated existing broker account: {}", uuid);
            } else {
                // New account with pre-set ID
                entityManager.persist(entity);
                log.debug("Persisted new broker account with preset ID: {}", uuid);
            }
        } else {
            // New account without ID - UUID will be generated by @PrePersist
            entityManager.persist(entity);
            log.debug("Persisted new broker account, generated ID: {}", entity.getId());
        }

        return mapper.toDomain(entity);
    }

    @Override
    public Optional<BrokerAccount> findById(BrokerAccountId id) {
        UUID uuid = id.value();
        log.debug("Finding broker account by ID: {}", uuid);

        return Optional.ofNullable(entityManager.find(BrokerAccountJpaEntity.class, uuid))
            .map(mapper::toDomain);
    }

    @Override
    public List<BrokerAccount> findByIds(Collection<BrokerAccountId> ids) {
        if (ids == null || ids.isEmpty()) {
            return List.of();
        }
        List<UUID> uuids = ids.stream()
            .map(BrokerAccountId::value)
            .distinct()
            .collect(Collectors.toList());
        log.debug("Batch-finding {} broker accounts by id", uuids.size());

        TypedQuery<BrokerAccountJpaEntity> query = entityManager.createQuery(
            "SELECT ba FROM BrokerAccountJpaEntity ba WHERE ba.id IN :ids",
            BrokerAccountJpaEntity.class
        );
        query.setParameter("ids", uuids);

        return query.getResultList()
            .stream()
            .map(mapper::toDomain)
            .collect(Collectors.toList());
    }

    @Override
    public List<BrokerAccount> findByUserId(UserId userId) {
        UUID uuid = userId.value();
        log.debug("Finding broker accounts by user ID: {}", uuid);

        TypedQuery<BrokerAccountJpaEntity> query = entityManager.createQuery(
            "SELECT ba FROM BrokerAccountJpaEntity ba WHERE ba.userId = :userId ORDER BY ba.createdAt DESC",
            BrokerAccountJpaEntity.class
        );
        query.setParameter("userId", uuid);

        return query.getResultList()
            .stream()
            .map(mapper::toDomain)
            .collect(Collectors.toList());
    }

    @Override
    @Transactional
    public void delete(BrokerAccountId id) {
        UUID uuid = id.value();
        log.debug("Deleting broker account: {}", uuid);

        BrokerAccountJpaEntity entity = entityManager.find(BrokerAccountJpaEntity.class, uuid);
        if (entity != null) {
            entityManager.remove(entity);
            log.debug("Deleted broker account: {}", uuid);
        } else {
            log.warn("Broker account not found for deletion: {}", uuid);
        }
    }

    @Override
    public boolean existsById(BrokerAccountId id) {
        UUID uuid = id.value();
        log.debug("Checking existence of broker account: {}", uuid);

        TypedQuery<Long> query = entityManager.createQuery(
            "SELECT COUNT(ba) FROM BrokerAccountJpaEntity ba WHERE ba.id = :id",
            Long.class
        );
        query.setParameter("id", uuid);

        return query.getSingleResult() > 0;
    }

    @Override
    public List<BrokerAccount> findAllByStatus(AccountStatus status) {
        log.debug("Finding broker accounts by status: {}", status);

        TypedQuery<BrokerAccountJpaEntity> query = entityManager.createQuery(
            "SELECT ba FROM BrokerAccountJpaEntity ba WHERE ba.status = :status ORDER BY ba.createdAt DESC",
            BrokerAccountJpaEntity.class
        );
        query.setParameter("status", status.name());

        return query.getResultList()
            .stream()
            .map(mapper::toDomain)
            .collect(Collectors.toList());
    }
}
