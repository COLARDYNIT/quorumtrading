package com.quorumtrading.adapter.persistence.entity;

import io.quarkus.hibernate.orm.panache.PanacheEntityBase;
import jakarta.persistence.*;
import org.hibernate.annotations.JdbcTypeCode;
import org.hibernate.type.SqlTypes;
import java.math.BigDecimal;
import java.time.Instant;
import java.util.UUID;

/**
 * JPA entity for LLMDecision persistence.
 *
 * Maps to the llm_decisions table created by Flyway migrations.
 * This is SEPARATE from the domain LLMDecision to maintain hexagonal architecture boundaries.
 *
 * Uses simple types (UUID, BigDecimal, String) instead of value objects (SimulationId, Percentage).
 * Mappers handle conversion between domain and persistence layers.
 */
@Entity
@Table(name = "llm_decisions")
public class LLMDecisionJpaEntity extends PanacheEntityBase {

    /**
     * Primary key (auto-generated by database).
     */
    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    @Column(name = "id")
    public Long id;

    /**
     * Simulation UUID (unwrapped from SimulationId value object).
     */
    @Column(name = "simulation_id", nullable = false)
    public UUID simulationId;

    /**
     * When the decision was made.
     */
    @Column(name = "decision_timestamp", nullable = false)
    public Instant decisionTimestamp;

    /**
     * Agent identifier (e.g., "technical-agent", "fundamental-agent").
     */
    @Column(name = "agent_id", length = 255, nullable = false)
    public String agentId;

    /**
     * Agent role (e.g., "TECHNICAL", "FUNDAMENTAL", "SENTIMENT").
     */
    @Column(name = "role", length = 255)
    public String role;

    /**
     * LLM model used (e.g., "qwen/qwen-2.5-coder-32b-instruct:free").
     */
    @Column(name = "llm_model", length = 255)
    public String llmModel;

    /**
     * Model the resolution chain asked for, when it differs from {@link #llmModel} — the model that
     * actually answered. NULL when they agree, so a non-null value marks a substitution.
     */
    @Column(name = "requested_model", length = 255)
    public String requestedModel;

    /**
     * Prompt sent to the LLM.
     */
    @Column(name = "prompt_used", columnDefinition = "TEXT")
    public String promptUsed;

    /**
     * Agent's reasoning (stored as JSONB).
     */
    @Column(name = "reasoning", nullable = false)
    @JdbcTypeCode(SqlTypes.JSON)
    public String reasoning;

    /**
     * Recommendation type as string (BUY, SELL, HOLD).
     */
    @Column(name = "recommendation", length = 255)
    public String recommendation;

    /**
     * Recommended action details (stored as JSONB).
     */
    @Column(name = "recommended_action")
    @JdbcTypeCode(SqlTypes.JSON)
    public String recommendedAction;

    /**
     * Confidence score (0.00 to 1.00, unwrapped from Percentage value object).
     */
    @Column(name = "confidence_score", precision = 38, scale = 2)
    public BigDecimal confidenceScore;

    /**
     * Execution time in milliseconds.
     */
    @Column(name = "execution_time_ms")
    public Integer executionTimeMs;

    // LLM cost tracking fields
    @Column(name = "prompt_tokens")
    public Integer promptTokens = 0;

    @Column(name = "completion_tokens")
    public Integer completionTokens = 0;

    @Column(name = "total_tokens")
    public Integer totalTokens = 0;

    @Column(name = "raw_cost_usd", precision = 18, scale = 8)
    public BigDecimal rawCostUsd = BigDecimal.ZERO;

    /**
     * Technical indicator snapshot at decision time (stored as JSONB).
     * Contains RSI, MACD, SMA, Bollinger Bands values for audit trail.
     */
    @Column(name = "indicator_snapshot")
    @JdbcTypeCode(SqlTypes.JSON)
    public String indicatorSnapshot;

    /**
     * Optional A2UI declarative UI payload (stored as JSONB).
     * Contains visual component descriptions for agent decision explanations.
     */
    @Column(name = "ui_payload")
    @JdbcTypeCode(SqlTypes.JSON)
    public String uiPayload;

    /**
     * Default constructor required by JPA.
     */
    public LLMDecisionJpaEntity() {
    }
}
