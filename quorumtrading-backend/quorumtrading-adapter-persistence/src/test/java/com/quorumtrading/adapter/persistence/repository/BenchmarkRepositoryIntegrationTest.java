    @Test
    @Transactional
    @DisplayName("shouldOrderByCreatedAtDesc_WhenFindingAllBenchmarks")
    void shouldOrderByCreatedAtDesc_WhenFindingAllBenchmarks() {
        // Arrange - Create benchmarks with different creation times
        Instant now = Instant.now();

        Benchmark oldest = new Benchmark(
            new BenchmarkId(UUID.randomUUID()),
            "Oldest",
            now.minus(30, ChronoUnit.DAYS),
            now,
            now.minus(3, ChronoUnit.HOURS),
            TEST_OWNER_ID
        );

        Benchmark middle = new Benchmark(
            new BenchmarkId(UUID.randomUUID()),
            "Middle",
            now.minus(30, ChronoUnit.DAYS),
            now,
            now.minus(2, ChronoUnit.HOURS),
            TEST_OWNER_ID
        );

        Benchmark newest = new Benchmark(
            new BenchmarkId(UUID.randomUUID()),
            "Newest",
            now.minus(30, ChronoUnit.DAYS),
            now,
            now.minus(1, ChronoUnit.HOURS),
            TEST_OWNER_ID
        );

        benchmarkRepository.save(oldest);
        benchmarkRepository.save(middle);
        benchmarkRepository.save(newest);

        // Act
        List<Benchmark> allBenchmarks = benchmarkRepository.findAll();

        // Assert - First 3 should be our newly created ones in DESC order
        assertThat(allBenchmarks).hasSizeGreaterThanOrEqualTo(3);

        // Find our test benchmarks in the result
        List<Benchmark> ourBenchmarks = allBenchmarks.stream()
            .filter(b -> b.getBenchmarkId().equals(newest.getBenchmarkId()) ||
                         b.getBenchmarkId().equals(middle.getBenchmarkId()) ||
                         b.getBenchmarkId().equals(oldest.getBenchmarkId()))
            .toList();

        assertThat(ourBenchmarks).hasSize(3);
        assertThat(ourBenchmarks.get(0).getBenchmarkId()).isEqualTo(newest.getBenchmarkId());
        assertThat(ourBenchmarks.get(1).getBenchmarkId()).isEqualTo(middle.getBenchmarkId());
        assertThat(ourBenchmarks.get(2).getBenchmarkId()).isEqualTo(oldest.getBenchmarkId());
    }

    // Helper method to create test benchmark
    private Benchmark createTestBenchmark(String name) {
        return new Benchmark(
            new BenchmarkId(UUID.randomUUID()),
            name,
            Instant.now().minus(30, ChronoUnit.DAYS),
            Instant.now(),
            Instant.now(),
            TEST_OWNER_ID
        );
    }
