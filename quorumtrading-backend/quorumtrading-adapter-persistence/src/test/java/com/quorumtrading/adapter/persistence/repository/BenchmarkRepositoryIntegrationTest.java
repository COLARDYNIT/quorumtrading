    UserRepository userRepository;

    private static final UserId TEST_OWNER_ID = new UserId(UUID.randomUUID());

    // Note: Using PostgreSQL with transactional tests
    // Each test gets rolled back automatically, ensuring clean state

    @Test
    @Transactional
    @DisplayName("shouldSaveAndRetrieveBenchmark_WhenValidBenchmarkProvided")
    void shouldSaveAndRetrieveBenchmark_WhenValidBenchmarkProvided() {
        // Arrange
        Instant startDate = Instant.now().minus(30, ChronoUnit.DAYS);
        Instant endDate = Instant.now();
        Benchmark benchmark = new Benchmark(
            new BenchmarkId(UUID.randomUUID()),
            "Test Benchmark",
            startDate,
            endDate,
            Instant.now(),
            TEST_OWNER_ID
        );

        // Act
        Benchmark saved = benchmarkRepository.save(benchmark);
        Optional<Benchmark> retrieved = benchmarkRepository.findById(saved.getBenchmarkId());

        // Assert
        assertThat(retrieved).isPresent();
        assertThat(retrieved.get().getBenchmarkId()).isEqualTo(benchmark.getBenchmarkId());
        assertThat(retrieved.get().getName()).isEqualTo("Test Benchmark");
        assertThat(retrieved.get().getStartDate()).isEqualTo(startDate);
        assertThat(retrieved.get().getEndDate()).isEqualTo(endDate);
        assertThat(retrieved.get().getCreatedAt()).isNotNull();
    }

