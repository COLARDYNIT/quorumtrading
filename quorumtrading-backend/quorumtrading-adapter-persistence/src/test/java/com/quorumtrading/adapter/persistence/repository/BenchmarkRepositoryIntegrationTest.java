    @Test
    @Transactional
    @DisplayName("shouldUpdateBenchmark_WhenBenchmarkExists")
    void shouldUpdateBenchmark_WhenBenchmarkExists() {
        // Arrange
        Instant originalStart = Instant.now().minus(30, ChronoUnit.DAYS);
        Instant originalEnd = Instant.now();
        Benchmark original = new Benchmark(
            new BenchmarkId(UUID.randomUUID()),
            "Original Name",
            originalStart,
            originalEnd,
            Instant.now(),
            TEST_OWNER_ID
        );
        Benchmark saved = benchmarkRepository.save(original);

        // Create updated version with same ID but different name and dates
        Instant newStart = Instant.now().minus(60, ChronoUnit.DAYS);
        Instant newEnd = Instant.now().minus(1, ChronoUnit.DAYS);
        Benchmark updated = new Benchmark(
            saved.getBenchmarkId(),
            "Updated Name",
            newStart,
            newEnd,
            saved.getCreatedAt(),
            TEST_OWNER_ID
        );

        // Act
        Benchmark result = benchmarkRepository.save(updated);
        Optional<Benchmark> retrieved = benchmarkRepository.findById(saved.getBenchmarkId());

        // Assert
        assertThat(retrieved).isPresent();
        assertThat(retrieved.get().getName()).isEqualTo("Updated Name");
        assertThat(retrieved.get().getStartDate()).isEqualTo(newStart);
        assertThat(retrieved.get().getEndDate()).isEqualTo(newEnd);
        assertThat(retrieved.get().getBenchmarkId()).isEqualTo(saved.getBenchmarkId());
    }

